#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES: the licence files of everything the released
# binary contains besides this project's own code. That is the Go standard
# library with its runtime, and the modules the build links.
#
#   scripts/notices.sh            write THIRD_PARTY_NOTICES
#   scripts/notices.sh <file>     write another file
#   scripts/notices.sh --check    fail when THIRD_PARTY_NOTICES is stale
#
# The modules come from `go list -deps` over ./cmd/ksrc-native for every
# release target, so a module that only one system links is listed too.
# KSRC_NATIVE_TARGETS overrides the targets, as in scripts/package.sh.
#
# Only the local Go installation and the local module cache are read. Nothing
# is downloaded: when a module is not in the cache the script stops.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

committed="THIRD_PARTY_NOTICES"
targets="${KSRC_NATIVE_TARGETS:-darwin/arm64 darwin/amd64 linux/arm64 linux/amd64}"
rule="================================================================================"
thin="--------------------------------------------------------------------------------"

export LC_ALL=C
export GOFLAGS=-mod=readonly
export GOPROXY=off
export CGO_ENABLED=0

fail() {
  echo "notices.sh: $*" >&2
  exit 1
}

# licence_files prints the licence files at the top of a directory, sorted.
licence_files() {
  find "$1" -maxdepth 1 -type f \( \
    -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'PATENTS*' \
    \) | sort
}

# section prints one heading and the given licence files, one path per line.
section() {
  local title="$1" files="$2" file
  echo
  echo "$rule"
  echo "$title"
  echo "$rule"
  while IFS= read -r file; do
    echo
    basename "$file"
    echo "$thin"
    # awk ends the last line with a newline when the file does not.
    awk 1 "$file"
  done <<< "$files"
}

# go_licence_files prints the LICENSE and PATENTS files of the Go
# installation. They are in GOROOT; Homebrew keeps LICENSE one level above.
# Both are looked up by name, so every installation gives the same section.
go_licence_files() {
  local goroot name dir found
  goroot="$(go env GOROOT)"
  for name in LICENSE PATENTS; do
    found=""
    for dir in "$goroot" "$goroot/.."; do
      if [ -f "$dir/$name" ]; then
        found="$dir/$name"
        break
      fi
    done
    [ -n "$found" ] || fail "no $name file in $goroot or above it; the licence of the Go standard library cannot be read"
    echo "$found"
  done
}

# linked_modules prints "<path> <version> <dir>" (tab separated) for every
# module of the build, over all targets, once.
linked_modules() {
  local target
  for target in $targets; do
    GOOS="${target%/*}" GOARCH="${target#*/}" go list -deps \
      -f '{{with .Module}}{{if not .Main}}{{.Path}}{{"\t"}}{{.Version}}{{"\t"}}{{.Dir}}{{end}}{{end}}' \
      ./cmd/ksrc-native ||
      fail "go list failed for $target; if a module is missing from the cache, run: go mod download"
  done | sort -u
}

generate() {
  local modules path version dir files
  modules="$(linked_modules)"
  [ -n "$modules" ] || fail "go list named no module"

  cat <<'EOF'
Third-party notices for ksrc-native

A released ksrc-native binary contains code of the Go standard library and of
the Go modules listed below. Each section gives the licence files of that
code, as its authors ship them. The licence of ksrc-native itself is in
LICENSE.txt.

This file is generated by scripts/notices.sh. Do not edit it by hand.
EOF

  section "Go standard library and runtime (https://go.dev)" "$(go_licence_files)"
  while IFS=$'\t' read -r path version dir; do
    [ -n "$dir" ] || fail "the module $path $version is not in the module cache; run: go mod download"
    files="$(licence_files "$dir")"
    [ -n "$files" ] || fail "no LICENSE, COPYING, NOTICE or PATENTS file in $dir ($path $version); add the notice by hand or drop the dependency"
    section "$path $version" "$files"
  done <<< "$modules"
}

case "${1:-}" in
  --check)
    fresh="$(mktemp)"
    trap 'rm -f "$fresh"' EXIT
    generate > "$fresh"
    if ! diff -u "$committed" "$fresh" > /dev/null 2>&1; then
      echo "notices.sh: $committed is stale: it differs from the licences of the modules the binary links" >&2
      diff -u "$committed" "$fresh" 2>&1 | head -40 >&2 || true
      echo "notices.sh: run scripts/notices.sh and commit the file" >&2
      exit 1
    fi
    echo "$committed is current"
    ;;
  -*)
    fail "unknown option $1; use --check or a file name"
    ;;
  *)
    out="${1:-$committed}"
    # Written to a temporary file first, so a failure leaves the old file.
    fresh="$(mktemp)"
    trap 'rm -f "$fresh"' EXIT
    generate > "$fresh"
    cp "$fresh" "$out"
    echo "wrote $out"
    ;;
esac
